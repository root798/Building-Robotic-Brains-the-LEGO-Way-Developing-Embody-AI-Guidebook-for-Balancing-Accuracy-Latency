#!/usr/bin/env python3
"""Build the four-domain catalog from full-validation metadata (CPU only).

Source directories are read-only. Only aggregate metrics, portable recipes and
file identities are exported; predictions, images and checkpoint binaries stay
outside the repository. Checkpoint files are hashed sequentially.
"""
